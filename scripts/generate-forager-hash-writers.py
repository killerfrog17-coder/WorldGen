"""Regenerate typed canonical writers from the runtime's checked public schema."""
import json
from pathlib import Path
import subprocess

root=Path(__file__).resolve().parent.parent
schemaPath=root/"artifacts/forager-hash-schema.json"
schemaPath.parent.mkdir(parents=True,exist_ok=True)
subprocess.run(["dotnet","build","tests/WorldGen.Core.Tests","-c","Release","--nologo"],cwd=root,check=True)
subprocess.run(["dotnet","tests/WorldGen.Core.Tests/bin/Release/net10.0/WorldGen.Core.Tests.dll","--forager-hash-schema",str(schemaPath)],cwd=root,check=True)
schema=json.loads(schemaPath.read_text())
scalar={"System.Int32":"PutInteger","System.Int64":"PutLong","System.Double":"PutDouble","System.Boolean":None}
lines=["// Generated by scripts/generate-forager-hash-writers.py; canonical field order is checked at startup.","using System;","using System.IO;","namespace WorldGen.Core","{","    public static partial class StateHash","    {","        static void CheckForagerHashRecords()","        {"]
for t in schema:
    fields=",".join(json.dumps(f["name"]+":"+f["type"]) for f in t["fields"])
    lines.append(f'            CheckRecord(typeof({t["name"]}),{fields});')
lines += ["        }","        static bool TryWriteForagerValue(BinaryWriter writer,object value)","        {"]
for t in schema:
    n=t["name"]
    lines.append(f'            if(value is {n}[] values{n}){{ForagerArray{n}(writer,values{n});return true;}}')
    lines.append(f'            if(value is {n} item{n}){{ForagerRecord{n}(writer,item{n},ForagerScratch{n}());return true;}}')
lines += ["            return false;","        }"]
for t in schema:
    n=t["name"];runs=[];items=[];pending=[]
    def finish():
        if pending:
            runs.append(list(pending));items.append(("block",len(runs)-1));pending.clear()
    for f in t["fields"]:
        if f["type"] in scalar:pending.append(f)
        else:finish();items.append(("field",f))
    finish()
    lines.append(f'        static readonly ScalarRecordBlock[] ForagerBlocks{n}={{')
    for run in runs:lines.append(f'            new ScalarRecordBlock(typeof({n}),'+",".join(json.dumps(f["name"]) for f in run)+"),")
    lines += ["        };",f'        static byte[][] ForagerScratch{n}()',f'        {{var result=new byte[ForagerBlocks{n}.Length][];for(int i=0;i<result.Length;i++)result[i]=(byte[])ForagerBlocks{n}[i].Bytes.Clone();return result;}}']
    lines += [f'        static void ForagerArray{n}(BinaryWriter writer,{n}[] records)',"        {",f'            writer.Write((byte)1);writer.Write("WorldGen.Core.{n}[]");var scratch=ForagerScratch{n}();',f'            foreach(var item in records){{writer.Write((byte)1);ForagerRecord{n}(writer,item,scratch);}}writer.Write((byte)0);',"        }"]
    lines += [f'        static void ForagerRecord{n}(BinaryWriter writer,{n} record,byte[][] scratch)',"        {",f'            if(record==null){{writer.Write((byte)0);return;}}writer.Write((byte)1);writer.Write("WorldGen.Core.{n}");']
    for kind,item in items:
        if kind=="block":
            for i,f in enumerate(runs[item]):
                op=scalar[f["type"]]
                if op:lines.append(f'            {op}(scratch[{item}],ForagerBlocks{n}[{item}].Offsets[{i}],record.{f["name"]});')
                else:lines.append(f'            scratch[{item}][ForagerBlocks{n}[{item}].Offsets[{i}]]=(byte)(record.{f["name"]}?1:0);')
            lines.append(f'            writer.Write(scratch[{item}]);')
        else:lines.append(f'            writer.Write("{item["name"]}");Write(writer,record.{item["name"]});')
    lines.append("        }")
lines += ["    }","}"]
(root/"src/WorldGen.Core/CanonicalForagerRecords.cs").write_text("\n".join(lines)+"\n")
