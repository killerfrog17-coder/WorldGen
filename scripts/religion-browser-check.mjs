import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const [source,output]=process.argv.slice(2);
if(!source||!output)throw Error('Usage: node scripts/religion-browser-check.mjs <new-rules.world> <output>');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'msedge',args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(String(e)));
async function status(){for(let n=0;n<120;n++){try{return JSON.parse(await page.evaluate(()=>window.__wg.people('status')));}catch{await page.waitForTimeout(250);}}throw Error('Worker remained busy');}
try{
 await page.goto(process.env.WORLDGEN_URL||'http://127.0.0.1:5092');
 await page.getByRole('button',{name:'Set Up World',exact:true}).click();
 await page.evaluate(async()=>{window.__wg=await import('/globe.js');});
 console.log('Loading actual structured-religion save in browser worker.');
 await page.evaluate(bytes=>window.__wg.loadWorldFile(bytes),(await fs.readFile(source)).toString('base64'));
 await page.waitForFunction(()=>document.querySelector('.error')?.textContent||[...document.querySelectorAll('button')].some(b=>b.textContent==='Start world'&&!b.disabled),{},{timeout:240000});
 const loadError=await page.locator('.error').allTextContents();if(loadError.length)throw Error(loadError.join('\n'));
 await page.getByRole('button',{name:'Start world',exact:true}).click();
 await page.waitForFunction(()=>window.__wg.viewInfo().map&&!window.__wg.viewInfo().loading,{},{timeout:180000});
 const initial=await status();
 await page.getByRole('button',{name:'Atlas',exact:true}).click();
 const atlas=page.getByRole('dialog',{name:'World atlas'});
 await atlas.getByRole('button',{name:'Religions',exact:true}).click();
 await atlas.locator('.atlas-directory-list button[data-kind="religion"]').first().click();
 await atlas.locator('.atlas-article[data-kind="religion"]').waitFor();
 await atlas.getByRole('button',{name:'People & place',exact:true}).click();
 await atlas.getByRole('button',{name:'Social teachings',exact:true}).click();
 await atlas.locator('.atlas-reading').getByText('Exclusive truth claims',{exact:true}).waitFor();
 await page.screenshot({path:output+'/doctrine.png'});
 await atlas.getByRole('button',{name:'Observance and sacred obligations',exact:true}).click();
 await atlas.locator('.atlas-reading').getByText('Ritual calendar',{exact:true}).waitFor();
 await page.screenshot({path:output+'/observance.png'});
 await atlas.getByRole('button',{name:'Ritual bodies',exact:true}).click();
 await atlas.locator('.atlas-directory-list button[data-kind="religious-body"]').first().click();
 await atlas.locator('.atlas-article[data-kind="religious-body"]').waitFor();
 const id=Number(await atlas.locator('.atlas-article').getAttribute('data-id'));
 await page.screenshot({path:output+'/institution.png'});
 await atlas.getByRole('button',{name:'Close',exact:true}).click();
 await page.getByRole('button',{name:'View',exact:true}).click();
 await page.getByLabel('Historical overlay',{exact:true}).selectOption('ReligiousInstitutions');
 await page.waitForTimeout(1000);const institutions=await status();
 assert.equal(institutions.Overlay,'ReligiousInstitutions');assert.ok(institutions.Legend.length>0);
 const selected=JSON.parse(await page.evaluate(cell=>window.__wg.people('select',cell),institutions.Legend[0].Cell));
 assert.equal(selected.Subject.Kind,'religious-body');assert.equal(selected.Subject.Id,institutions.Legend[0].ColorId);
 const document=JSON.parse(await page.evaluate(id=>window.__wg.people('atlas:religious-body',id),id));
 await page.getByRole('button',{name:'View',exact:true}).click();
 await page.locator('canvas').first().hover();await page.mouse.wheel(0,-700);await page.waitForTimeout(350);
 await page.evaluate(d=>window.__wg.focusAtlas(d.Longitude,d.Latitude),document);await page.waitForTimeout(300);
 await page.screenshot({path:output+'/institutions-map.png'});
 assert.equal(selected.Seconds,initial.Seconds);assert.equal(errors.length,0,errors.join('\n'));
 await fs.writeFile(output+'/result.json',JSON.stringify({institutionCount:institutions.Legend.length,subject:selected.Subject,errors},null,2));
 console.log('PASS browser: doctrine/observance/institution atlas UI, independent institution map, correct clicked subject, paused time, no JS errors.');
}catch(error){console.log('Browser errors:',JSON.stringify(errors));console.log((await page.locator('body').innerText()).slice(-3500));await page.screenshot({path:output+'/failure.png'});throw error;}
finally{await browser.close();}
