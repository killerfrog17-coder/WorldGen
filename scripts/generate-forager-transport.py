"""Generate checked, lossless hot-record save codecs from the public Core schema."""
import hashlib
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
schema_path = root / 'artifacts/forager-transport-schema.json'
schema_path.parent.mkdir(parents=True, exist_ok=True)
subprocess.run(['dotnet', 'build', 'tests/WorldGen.Core.Tests', '-c', 'Release', '--nologo'], cwd=root, check=True)
subprocess.run(['dotnet', 'tests/WorldGen.Core.Tests/bin/Release/net10.0/WorldGen.Core.Tests.dll', '--forager-hash-schema', str(schema_path)], cwd=root, check=True)
schema = json.loads(schema_path.read_text())
lines = ['// Generated by scripts/generate-forager-transport.py. Do not edit field order by hand.',
         'using System;', 'using System.IO;', 'using WorldGen.Core;',
         'namespace WorldGen.Serialization', '{', '    public static partial class PackedForagerRecords', '    {',
         '        static PackedForagerRecords()', '        {']
for t in schema:
    fields = ','.join(json.dumps(f['name'] + ':' + f['type']) for f in t['fields'])
    lines.append(f'            CheckSchema(typeof({t["name"]}),{fields});')
lines += ['        }']
for t in schema[:2]:
    n = t['name']
    signature = hashlib.sha256(json.dumps(t, sort_keys=True).encode()).hexdigest()[:16]
    lines += [f'        public static byte[] Pack({n} value,System.Threading.CancellationToken token=default)',
              '        {', '            if(value==null)return null;',
              '            token.ThrowIfCancellationRequested();',
              '            using(var memory=new MemoryStream(2048))', '            using(var writer=new BinaryWriter(memory))',
              '            {', f'                writer.Write(0x{signature}UL);']
    for f in t['fields']:
        name, typ = f['name'], f['type']
        op = {'System.Double[]':'WriteDoubles', 'System.Int32[]':'WriteIntegers', 'WorldGen.Core.ForagerAffiliation[]':'WriteAffiliations', 'System.String':'WriteString'}.get(typ)
        if op:
            lines.append(f'                {op}(writer,value.{name},token);')
        elif typ.startswith('WorldGen.Core.'):
            lines.append(f'                writer.Write((int)value.{name});')
        else:
            assert typ in ('System.Int32','System.Int64','System.Double')
            lines.append(f'                writer.Write(value.{name});')
    lines += ['                CheckLength(memory.Length);return memory.ToArray();', '            }', '        }',
              f'        public static {n} Unpack{n.removeprefix("Forager")}(byte[] data,System.Threading.CancellationToken token=default)',
              '        {', '            if(data==null)return null;', '            token.ThrowIfCancellationRequested();CheckLength(data.Length);',
              '            using(var memory=new MemoryStream(data,false))', '            using(var reader=new BinaryReader(memory))', '            {',
              f'                if(reader.ReadUInt64()!=0x{signature}UL)throw new System.Runtime.Serialization.SerializationException("Unsupported forager record schema.");',
              f'                var value=new {n}();']
    for f in t['fields']:
        name, typ = f['name'], f['type']
        op = {'System.Double[]':'ReadDoubles(reader,token)', 'System.Int32[]':'ReadIntegers(reader,token)', 'WorldGen.Core.ForagerAffiliation[]':'ReadAffiliations(reader,token)', 'System.String':'ReadString(reader,token)', 'System.Int32':'reader.ReadInt32()', 'System.Int64':'reader.ReadInt64()', 'System.Double':'reader.ReadDouble()'}.get(typ)
        if op is None:
            assert typ.startswith('WorldGen.Core.')
            op=f'({typ})reader.ReadInt32()'
        lines.append(f'                value.{name}={op};')
    lines += ['                if(memory.Position!=memory.Length)throw new System.Runtime.Serialization.SerializationException("Trailing forager record data.");',
              '                return value;', '            }', '        }']
lines += ['    }', '}']
(root/'src/WorldGen.Serialization/PackedForagerRecords.Generated.cs').write_text('\n'.join(lines)+'\n')
