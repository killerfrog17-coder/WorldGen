"""Create an isolated, camera-viewable Kimodo audition on approved MPFB people.

Only writes the new demo. Original bodies, rigs, materials, weights, and game
packages are read-only. Grips and a spear release are explicit preview fitting,
not represented as finger or prop motion generated by Kimodo.
"""
