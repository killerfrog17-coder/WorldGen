def material(name, color, roughness=.75):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1)
    mat.use_nodes = True
    p = mat.node_tree.nodes.get('Principled BSDF')
    p.inputs['Base Color'].default_value = (*color, 1)
    p.inputs['Roughness'].default_value = roughness
    return mat


def move_to(obj, col):
    for old in list(obj.users_collection):
        old.objects.unlink(obj)
    col.objects.link(obj)


def cylinder(name, radius, length, mat, col, vertices=12):
    bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=length)
    ob = bpy.context.object
    ob.name = name
    ob.data.materials.append(mat)
    move_to(ob, col)
    return ob


def make_spear(letter, col):
    root = bpy.data.objects.new('Demo spear ' + letter, None)
    col.objects.link(root)
    root.empty_display_size = .05
    shaft = cylinder('Wooden spear shaft ' + letter, .0133, 1.95, WOOD, col)
    shaft.parent = root
    shaft.location.z = .17
    bpy.ops.mesh.primitive_cone_add(vertices=4, radius1=.043, radius2=0, depth=.23)
    tip = bpy.context.object
    tip.name = 'Stone spear tip ' + letter
    tip.parent = root
    tip.location = (0, 0, 1.25)
    tip.scale = (.45, 1, 1)
    tip.data.materials.append(STONE)
    move_to(tip, col)
    return root, [shaft, tip]


def headless_copy(obj, col):
    copy = obj.copy()
    copy.data = obj.data.copy()
    copy.name = obj.name + ' — local head concealed'
    col.objects.link(copy)
    groups = {g.index for g in copy.vertex_groups if g.name in {'head', 'neck_01'}}
    remove = {v.index for v in copy.data.vertices if sum(g.weight for g in v.groups if g.group in groups) > .55}
    bm = bmesh.new()
    bm.from_mesh(copy.data)
    bm.verts.ensure_lookup_table()
    bmesh.ops.delete(bm, geom=[v for v in bm.verts if v.index in remove], context='VERTS')
    bm.to_mesh(copy.data)
    bm.free()
    return copy


def set_action(rig, action):
    rig.animation_data_create()
    rig.animation_data.action = action
    rig.animation_data.action_slot = action.slots[0]
    for bone in rig.pose.bones:
        bone.location = (0, 0, 0)
        bone.scale = (1, 1, 1)


def fit_fingers(rig, action, clip, grip, relaxed, release):
    bag = action.layers[0].strips[0].channelbag(action.slots[0])
    for curve in bag.fcurves:
        bone = curve.data_path.split('"')[1]
        if not bone.startswith(('index_', 'middle_', 'ring_', 'pinky_', 'thumb_')):
            continue
        for key in curve.keyframe_points:
            frame = key.co.x
            amount = 1 if clip != 'empty_walk' and bone.endswith('_r') else 0
            if clip == 'spear_throw':
                amount *= 1 - max(0, min(1, (frame - release + 1) / 4))
            q = relaxed[bone].slerp(grip[bone], amount)
            key.co.y = q[curve.array_index]


def attachment(rig, side='r'):
    """Shaft crosses a power grip across the knuckles, not along the fingers."""
    hand = rig.pose.bones['hand_' + side].matrix
    index = rig.pose.bones['index_01_' + side].head
    pinky = rig.pose.bones['pinky_01_' + side].head
    middle = rig.pose.bones['middle_01_' + side].head
    axis = (index - pinky).normalized()
    # For a right-hand overarm grip the point leads forward at release.
    if side == 'r':
        axis = -axis
    length = (middle - hand.translation).length
    center = hand.translation.lerp(middle, .69)
    normal = (middle - hand.translation).cross(index - pinky).normalized()
    center += normal * (length * .15)
    orientation = axis.to_track_quat('Z', 'Y')
    return Matrix.LocRotScale(center, orientation, Vector((1, 1, 1)))


def fit_wrist_roll(rig, action, clip, release, frames):
    """Fit prop orientation at the wrist; keep generated elbow/hand path."""
    if clip == 'empty_walk':
        return
    set_action(rig, action)
    rows = []
    previous = None
    target = Vector((0, 0, 1)) if clip == 'spear_walk' else Vector((0, -1, .12)).normalized()
    for frame in range(1, frames + 1):
        bpy.context.scene.frame_set(frame)
        bpy.context.view_layer.update()
        hand = rig.pose.bones['hand_r']
        shaft = attachment(rig).to_3x3().col[2]
        amount = 1.0 if clip == 'spear_walk' else 1 - max(0, min(1, (frame - release) / 10))
        correction = Quaternion().slerp(shaft.rotation_difference(target), amount)
        desired = correction @ hand.matrix.to_quaternion()
        restlocal = hand.parent.bone.matrix_local.inverted() @ hand.bone.matrix_local
        q = (restlocal.inverted() @ hand.parent.matrix.inverted() @ desired.to_matrix().to_4x4()).to_quaternion()
        if previous is not None and previous.dot(q) < 0:
            q.negate()
        rows.append(tuple(q))
        previous = q.copy()
    bag = action.layers[0].strips[0].channelbag(action.slots[0])
    for curve in bag.fcurves:
        if curve.data_path == 'pose.bones["hand_r"].rotation_quaternion':
            for key, q in zip(curve.keyframe_points, rows):
                key.co.y = q[curve.array_index]
    action['prop_fitting'] = 'Wrist orientation, fingers and prop flight fitted separately; generated arm path unchanged'


def animate_spear(rig, spear, action, clip, release, frames):
    set_action(rig, action)
    spear.animation_data_clear()
    spear.animation_data_create()
    spear.animation_data.action = bpy.data.actions.new('Spear ' + rig['variant'] + ' | ' + clip)
    poses = []
    for frame in range(1, frames + 1):
        bpy.context.scene.frame_set(frame)
        bpy.context.view_layer.update()
        poses.append(rig.matrix_world @ attachment(rig))
    reference = poses[max(0, release - 1)] if clip == 'spear_throw' else poses[0]
    axis = reference.to_3x3().col[2]
    forward = Vector((0, -1, 0)) if clip == 'spear_throw' else Vector((0, 0, 1))
    if axis.dot(forward) < 0:
        poses = [pose @ Matrix.Rotation(math.pi, 4, 'X') for pose in poses]
    if clip == 'spear_throw':
        index = max(1, release - 1)
        start = poses[index].translation.copy()
        start_orientation = poses[index].to_quaternion()
        # Physical demonstration flight begins at the animated grip position.
        velocity = (poses[index].translation - poses[index - 1].translation) * 30
        if velocity.length < 5:
            velocity = Vector((0, -12, 4))
        else:
            velocity = velocity.normalized() * max(12, min(22, velocity.length))
        velocity.z = max(velocity.z, 2.2)
        for i in range(index, frames):
            t = (i - index) / 30
            point = start + velocity * t + Vector((0, 0, -4.905 * t * t))
            direction = velocity + Vector((0, 0, -9.81 * t))
            rotation = start_orientation.slerp(direction.to_track_quat('Z', 'Y'), min(1, t * 5))
            poses[i] = Matrix.LocRotScale(point, rotation, Vector((1, 1, 1)))
    spear.rotation_mode = 'QUATERNION'
    previous = None
    for frame, pose in enumerate(poses, 1):
        spear.location = pose.translation
        q = pose.to_quaternion()
        if previous is not None and previous.dot(q) < 0:
            q.negate()
        previous = q.copy()
        spear.rotation_quaternion = q
        spear.keyframe_insert('location', frame=frame)
        spear.keyframe_insert('rotation_quaternion', frame=frame)
    spear.animation_data.action.name = 'Spear ' + rig['variant'] + ' | ' + clip
    spear.animation_data.action.use_fake_user = True
    for curve in spear.animation_data.action.layers[0].strips[0].channelbag(spear.animation_data.action.slots[0]).fcurves:
        for key in curve.keyframe_points:
            key.interpolation = 'LINEAR'
    return spear.animation_data.action.name


def main():
    global WOOD, STONE
    ap = argparse.ArgumentParser()
    ap.add_argument('--variants', default='ABCDEF')
    ap.add_argument('--partial', action='store_true')
    args = ap.parse_args(sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else [])
    source_sha = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    motions = {}
    for case in ['empty_walk', 'spear_walk', 'spear_throw']:
        folder = ROOT / 'motions' / case
        candidates = sorted(folder.glob('seed-*/generation.json')) if folder.exists() else []
        if not candidates:
            if args.partial:
                continue
            raise RuntimeError('Requested motion is not ready: ' + case)
        preferred = folder / 'selected.json'
        take = folder / json.loads(preferred.read_text())['take'] if preferred.exists() else candidates[0].parent
        motions[case] = SomaMotion(take)
    reports = [movement_report(motion) for motion in motions.values()]
    (ROOT / 'raw-motion-analysis.json').write_text(json.dumps(reports, indent=2))
    bpy.ops.wm.open_mainfile(filepath=str(SOURCE))
    bpy.context.preferences.filepaths.save_version = 0
    scene = bpy.context.scene
    # The selected package and all approved authoring files remain untouched.
    keep = {o for c in bpy.data.collections if c.name in ['MPFB_' + v for v in args.variants] for o in c.objects}
    for obj in list(bpy.data.objects):
        if obj not in keep:
            bpy.data.objects.remove(obj, do_unlink=True)
    rigs_col = bpy.data.collections.new('Demo rigs')
    scene.collection.children.link(rigs_col)
    props = bpy.data.collections.new('Demo equipment')
    scene.collection.children.link(props)
    env = bpy.data.collections.new('Demo clearing')
    scene.collection.children.link(env)
    WOOD = material('Demo spear wood', (.24, .12, .055), .82)
    STONE = material('Demo flint', (.16, .18, .19), .45)
    spec = importlib.util.spec_from_file_location('kimodo_native_retarget', REPO / 'scripts/build-human-animation-preview.py')
    retarget = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(retarget)
    retarget.source_map = lambda source: SOMA_MAP
    retarget.rotation_fix = retarget_fix
    samples = {name: [motion.sample(None, i / 30) for i in range(motion.info['frames'])] for name, motion in motions.items()}
    evidence = []
    for letter in args.variants:
        col = bpy.data.collections['MPFB_' + letter]
        col.hide_viewport = False
        col.hide_render = False
        rig = next(o for o in col.objects if o.type == 'ARMATURE')
        rig.hide_set(False)
        rig.hide_render = True
        rig['variant'] = letter
        rig.location = (0, 0, 0)
        rig['demo_eye'] = list(col['head_center'])
        move_to(rig, rigs_col)
        for ob in col.objects:
            ob.hide_set(False)
            ob.hide_render = False
            if ob.type == 'MESH':
                for modifier in ob.modifiers:
                    if modifier.type == 'SUBSURF':
                        modifier.show_viewport = False
                        modifier.show_render = False
        grip_action = next(a for a in bpy.data.actions if a.name == 'MPFB ' + letter + ' | Sword attack')
        set_action(rig, grip_action)
        scene.frame_set(12)
        bpy.context.view_layer.update()
        grip = {b.name: b.rotation_quaternion.copy() for b in rig.pose.bones
                if b.name.startswith(('thumb_', 'index_', 'middle_', 'ring_', 'pinky_'))}
        idle_action = bpy.data.actions['MPFB ' + letter + ' | Idle']
        set_action(rig, idle_action)
        scene.frame_set(1)
        bpy.context.view_layer.update()
        relaxed = {b.name: b.rotation_quaternion.copy() for b in rig.pose.bones
                   if b.name in grip}
        first = bpy.data.collections.new('First person ' + letter)
        scene.collection.children.link(first)
        for ob in list(col.objects):
            if ob.type == 'MESH' and ob.name.endswith('.body'):
                headless_copy(ob, first)
            elif ob.type == 'MESH' and 'suit' in ob.name:
                duplicate = ob.copy()
                duplicate.name = ob.name + ' — local clothing'
                first.objects.link(duplicate)
        spear, parts = make_spear(letter, props)
        spear['variant'] = letter
        clips = []
        for name, motion in motions.items():
            report = next(r for r in reports if r['id'] == name)
            release = 0
            if name == 'spear_throw':
                points = np.array(report['right_hand'])
                velocity = -np.diff(points[:, 1]) * 30
                score = velocity * np.clip((points[1:, 2] - .85) / .4, 0, 1)
                release = int(np.argmax(score)) + 2
                release = max(8, min(len(points) - 10, release))
            record = retarget.animate(rig, 'MPFB', (name, motion, name), samples[name])
            action = bpy.data.actions[record['action']]
            action.name = 'Kimodo ' + letter + ' | ' + name
            record['action'] = action.name
            action['motion_origin'] = 'Kimodo generated; native bind retarget; grip fitted separately'
            fit_fingers(rig, action, name, grip, relaxed, release)
            fit_wrist_roll(rig, action, name, release, record['frames'])
            record['release_frame'] = release
            record['spear_action'] = animate_spear(rig, spear, action, name, release, record['frames'])
            record['raw_take'] = str(motion.folder.relative_to(REPO))
            clips.append(record)
        rig['kimodo_clips'] = json.dumps(clips)
        spear['parts'] = json.dumps([o.name for o in parts])
        evidence.append({'variant': letter, 'rig': rig.name, 'clips': clips, 'bones': len(rig.data.bones)})
        print('KIMODO FITTED', letter, flush=True)

    ground = material('Clearing soil', (.16, .21, .105))
    bpy.ops.mesh.primitive_plane_add(size=120)
    floor = bpy.context.object
    floor.name = 'Demo clearing ground'
    floor.data.materials.append(ground)
    move_to(floor, env)
    trail = material('Trail sand', (.28, .235, .16))
    bpy.ops.mesh.primitive_plane_add(size=2, location=(0, -20, .001))
    path = bpy.context.object
    path.name = 'Demo walking path'
    path.scale = (1.3, 26, 1)
    path.data.materials.append(trail)
    move_to(path, env)
    for x in [-2.5, 2.5]:
        for y in [-5, -12, -20]:
            ob = cylinder('Distance marker', .09, 1, WOOD, env)
            ob.location = (x, y, .5)
    bpy.ops.object.camera_add(location=(0, -.12, 1.6))
    camera = bpy.context.object
    camera.name = 'Kimodo review camera'
    camera.data.clip_start = .035
    camera.data.clip_end = 300
    scene.camera = camera
    move_to(camera, env)
    bpy.ops.object.light_add(type='SUN', location=(0, 0, 8))
    sun = bpy.context.object
    sun.rotation_euler = (.45, -.35, -.4)
    sun.data.energy = 2.3
    sun.data.angle = math.radians(12)
    move_to(sun, env)
    bpy.ops.object.light_add(type='AREA', location=(1, -3, 5))
    fill = bpy.context.object
    fill.rotation_euler = (Vector((0, 0, 1)) - fill.location).to_track_quat('-Z', 'Y').to_euler()
    fill.data.energy = 350
    fill.data.shape = 'DISK'
    fill.data.size = 5
    move_to(fill, env)
    world = bpy.data.worlds.new('Demo daylight')
    world.use_nodes = True
    world.node_tree.nodes['Background'].inputs[0].default_value = (.55, .68, .85, 1)
    world.node_tree.nodes['Background'].inputs[1].default_value = .55
    scene.world = world
    scene.render.engine = 'BLENDER_EEVEE_NEXT'
    scene.render.resolution_x = 1280
    scene.render.resolution_y = 720
    scene.render.resolution_percentage = 100
    scene.render.fps = 30
    scene.render.fps_base = 1
    scene.view_settings.view_transform = 'AgX'
    scene['kimodo_variant'] = 'B' if 'B' in args.variants else args.variants[0]
    scene['kimodo_clip'] = 'empty_walk'
    scene['kimodo_view'] = 'first'
    scene['kimodo_pitch'] = -15.0
    scene['kimodo_skeleton'] = False
    scene['kimodo_variants'] = args.variants
    scene['kimodo_source_sha'] = source_sha
    scene['kimodo_note'] = 'Generated body motion; fitted grip and demonstration spear flight. Separate audition, not installed in game.'
    # Discard unused action datablocks in this new file only.
    used = {c['action'] for r in evidence for c in r['clips']} | {c['spear_action'] for r in evidence for c in r['clips']}
    for action in list(bpy.data.actions):
        if action.name not in used:
            bpy.data.actions.remove(action)
    import kimodo_demo_stage as stage
    stage.refresh()
    stage.select_clip('empty_walk')
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type == 'VIEW_3D':
                space = area.spaces.active
                space.region_3d.view_perspective = 'CAMERA'
                space.region_3d.view_camera_zoom = 0
                space.show_region_ui = True
                space.overlay.show_overlays = False
                space.shading.type = 'MATERIAL'
                space.shading.use_scene_world = True
                space.shading.use_scene_lights = True
    bpy.ops.wm.save_as_mainfile(filepath=str(ROOT / 'Kimodo - First Person Demo.blend'))
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != source_sha:
        raise RuntimeError('Approved source changed during demo creation')
    (ROOT / 'build-evidence.json').write_text(json.dumps({'source_sha256': source_sha, 'people': evidence,
                                                        'source_unchanged': True, 'game_modified': False}, indent=2))
    print('KIMODO DEMO BUILT', flush=True)


if __name__ == '__main__':
    main()
