REPO = Path(__file__).resolve().parent.parent
ROOT = REPO / 'artifacts/kimodo-first-person-demo'
SOURCE = REPO / 'artifacts/human-animation-preview/Human - Animation Comparison.blend'
sys.path.insert(0, str(REPO / 'scripts'))
